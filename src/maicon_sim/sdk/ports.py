"""Participant contracts contain no evaluator world types."""
from typing import Protocol, Any, Mapping, Sequence


class ParticipantPort(Protocol):
    async def get_me(self) -> dict: ...
    async def ready(self) -> dict: ...
    async def await_order(self, wait_s:int=120) -> dict: ...
    async def await_target(self, wait_s:int=120) -> dict: ...
    async def submit_m1(self, value:Mapping[str,Any]) -> dict: ...
    async def submit_m3(self, value:Mapping[str,Any]) -> dict: ...
    async def submit_m6(self, ranking:Sequence[str]) -> dict: ...
    async def latest_observations(self) -> dict: ...
    async def command_velocity(self, linear_x_mps:float, angular_z_rps:float) -> dict: ...
    async def command_gimbal(self,pan_units:float,tilt_units:float,speed_deg_s:float,acc_units:float) -> dict: ...
    async def fire(self) -> dict: ...
    async def drone(self, camera=None) -> tuple[bytes, dict]: ...
